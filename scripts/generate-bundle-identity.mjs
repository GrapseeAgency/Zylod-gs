// F1/F5 provenance contract — generates src/generated/bundle-identity.ts.
//
// Every web bundle build bakes its EXACT identity (commit, version, builtAt)
// into the bundle. The native shells read window.__ZylodBundleIdentity after
// every document load and refuse to silently accept a wrong/stale/unknown
// bundle (owner remediation order F1: "A wrong/stale/unknown bundle must
// never be silently accepted", F5: "permanent provenance visibility").
//
// - ZYLOD_WEB_COMMIT / ZYLOD_WEB_VERSION / ZYLOD_WEB_BUILT_AT override the
//   detection (CI/deploy pipelines can pin the deployed commit explicitly).
// - Fallback is the git HEAD of the tree the bundle was built from.
// - The file is only rewritten when its content changes, so `next dev` is
//   not restarted by an identical regeneration.
import { execSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const outFile = resolve(repoRoot, 'src/generated/bundle-identity.ts')

function gitCommit() {
  try {
    return execSync('git rev-parse HEAD', { cwd: repoRoot, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim()
  } catch {
    return ''
  }
}

const commit = process.env.ZYLOD_WEB_COMMIT || gitCommit() || 'unknown'
const shortCommit = commit === 'unknown' ? 'unknown' : commit.slice(0, 7)
const version = process.env.ZYLOD_WEB_VERSION || '2.4.5'
const builtAt = process.env.ZYLOD_WEB_BUILT_AT || new Date().toISOString()

const content = `// AUTO-GENERATED by scripts/generate-bundle-identity.mjs — do not edit.
// Build-time identity of THIS deployed web bundle (F1/F5 provenance).
// The native shells surface this via window.__ZylodBundleIdentity and
// compare it against their own build commit (docs/PROVENANCE.md).
export const BUNDLE_IDENTITY = {
  commit: ${JSON.stringify(commit)},
  shortCommit: ${JSON.stringify(shortCommit)},
  version: ${JSON.stringify(version)},
  builtAt: ${JSON.stringify(builtAt)},
} as const;

export type BundleIdentity = typeof BUNDLE_IDENTITY;
`

mkdirSync(dirname(outFile), { recursive: true })
if (existsSync(outFile) && readFileSync(outFile, 'utf8') === content) {
  process.exit(0)
}
writeFileSync(outFile, content)
console.log(`[bundle-identity] commit=${shortCommit} version=${version} builtAt=${builtAt}`)
